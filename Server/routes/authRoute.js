import express from 'express';
import { requireSignIn } from '../middleware/authmiddleware.js';
import { forgotpasswordcontroller, loginController, mailcontroller, registerController, verifyotpcontroller, getpasswordcontroller,changepasswordcontroller, verifychangepasswordcontroller, contactcontroller, islogincontroller, deleteusercontroller, logoutcontroller } from '../controllers/authcontroller.js';
import { authLimiter, otpLimiter } from '../middleware/security.js';
const router=express.Router();
router.post("/register",authLimiter,registerController);
router.post("/login",authLimiter,loginController);
router.post("/sendotp",otpLimiter,requireSignIn,mailcontroller);
router.post("/verifyotp",otpLimiter,verifyotpcontroller);
router.post("/forgotpassword",otpLimiter,forgotpasswordcontroller);
router.post("/recievepassword/:success",otpLimiter,getpasswordcontroller);
router.post("/changepassword",authLimiter,requireSignIn,changepasswordcontroller);
router.post("/verifychangepassword/:success",authLimiter,requireSignIn,verifychangepasswordcontroller);
router.post("/contact",requireSignIn,contactcontroller);
router.post("/islogin",requireSignIn,islogincontroller);
router.post("/deleteuser",requireSignIn,deleteusercontroller);
router.post("/logout",logoutcontroller);
export default router;
